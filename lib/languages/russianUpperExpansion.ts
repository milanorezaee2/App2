function buildUpperLevel(
  level: 3 | 4,
  modules: readonly UpperModuleSpec[],
  prefix: string,
  actions: readonly RuAction[],
): LearningLesson[] {
  return modules.map((spec, index) => {
    const order = level === 3 ? 96 + index : 106 + index;
    const id = `ru-l${level + 1}-module-${String(index + 1).padStart(2, '0')}`;
    const firstItem = spec.items[0];
    return createFullRussianLesson({
      id,
      order,
      level,
      title: spec.title,
      subtitle: spec.goal,
      goal: spec.goal,
      explanation: level === 3
        ? [
            'در این سطح جمله‌های کوتاه را به روایت و توضیح چندبخشی پیوند می‌دهید؛ از потому́ что، хотя́، кото́рый، е́сли бы و поэ́тому برای روشن‌کردن رابطهٔ دقیق ایده‌ها استفاده کنید.',
            `واژگان محوری این درس بر موضوع «${spec.title}» متمرکز است تا هر ساختار دستوری در بافت واقعی خود تمرین شود.`,
          ]
        : [
            'در این سطح لحن رسمی، بندهای وابسته، وجه وصفی (Прича́стие)، قید فعلی (Дееприча́стие) و استدلال چندمرحله‌ای به کار می‌روند.',
            `تمامی جمله‌های این درس با واژگان تخصصی حوزهٔ «${spec.title}» ساخته شده‌اند تا بیان تحلیلی و دقیق تقویت شود.`,
          ],
      idPrefix: `${prefix}${String(index + 1).padStart(2, '0')}`,
      levelTier: level,
      placePhraseRu: spec.placeRu,
      placePhraseFa: spec.placeFa,
      items: spec.items,
      actions,
      dialogue: spec.dialogue.map(([speaker, text, fa]) => ({ speaker, text, fa })),
      checks: [
        {
          promptFa: `عبارت کلیدی «${firstItem.nom}» در درس «${spec.title}» به چه معناست؟`,
          choices: [firstItem.fa, 'تخفیف فصلی فروشگاه', 'برنامهٔ حرکت قطار شهری'],
          correctIndex: 0,
          explanationFa: `«${firstItem.nom}» به معنای «${firstItem.fa}» است.`,
        },
        {
          promptFa: `هدف ارتباطی اصلی درس «${spec.title}» کدام است؟`,
          choices: [spec.goal, 'حفظ فهرست واژه‌های جدا از جمله', 'ترجمهٔ واژه‌به‌واژه بدون توجه به بافت'],
          correctIndex: 0,
          explanationFa: `در این درس تمرکز بر «${spec.goal}» است.`,
        },
      ],
    });
  });
}

export function expandUpperRussianLessons() {
  return {
    communication: buildUpperLevel(3, B1_MODULES, 'ru3b', B1_ACTIONS),
    advanced: buildUpperLevel(4, B2_MODULES, 'ru4b', B2_ACTIONS),
  };
}
